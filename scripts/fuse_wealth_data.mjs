function mapLeverage(model, name) {
  switch (model) {
    case "时间与体力": return "labor";
    case "专业技能": return "labor";
    case "信息差与价差": return "arbitrage";
    case "连接与撮合": return "arbitrage";
    case "注意力与信任": return "attention";
    case "风险承担": return "capital";
    case "规则与资质": return "rent";
    case "资本与资产":
      if (/股票|债券|指数|放贷|典当|利息|私募|VC|PE/.test(name)) return "capital";
      if (/土地|房屋|租|矿|牌照|油/.test(name)) return "rent";
      return "product";
    default: return "labor";
  }
}

function mapScalability(s) {
  if (s === "高") return 5;
  if (s === "中") return 3;
  if (s === "低") return 2;
  return 1;
}

function isSoloFriendly(g, v, n) {
  if (v === "非法" || v === "已死") return false;
  if (/牌照|大额本金|重资本|政企关系|募资能力|皇权特许|大数定律|组织·成本/.test(g)) return false;
  if (/商业银行|保险 \/ 再保险|特许经营|私募 \/ VC|招投标|官俸/.test(n)) return false;
  return true;
}

function extractFormula(l, m) {
  const match = l.match(/收入\s*=\s*[^，；。]+|利润\s*=\s*[^，；。]+|超额收益\s*=\s*[^，；。]+|期望收益\s*=\s*[^，；。]+/);
  if (match) return match[0];
  const st = STRUCTURES.find(s => s.name === m);
  return st ? st.formula : "收入 = 交付价值 × 交易频次";
}

